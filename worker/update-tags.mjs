// Refreshes src/tags.js from Scryfall's list of Tagger tags (https://scryfall.com/docs/tagger-tags).
// Usage, in the worker folder: node update-tags.mjs   then   npx wrangler deploy
// Keeps the oracle (function) tags and drops "cycle-…" tags, which only group cards of one set's cycle.
import { writeFileSync } from "node:fs";

const res = await fetch("https://scryfall.com/docs/tagger-tags", {
  headers: { "User-Agent": "ScryfallZoekhulp/1.0", Accept: "text/html" }
});
if (!res.ok) throw new Error(`Scryfall returned ${res.status}`);
const html = await res.text();

const tags = [...new Set([...html.matchAll(/oracletag%3A([a-z0-9-]+)/g)].map(m => m[1]))]
  .filter(t => !t.startsWith("cycle-"))
  .sort();
if (tags.length < 1000) throw new Error(`Only ${tags.length} tags found; the page layout may have changed.`);

writeFileSync(new URL("./src/tags.js", import.meta.url),
  `// Generated by update-tags.mjs from https://scryfall.com/docs/tagger-tags on ${new Date().toISOString().slice(0, 10)}.\n` +
  `// Scryfall Tagger oracle tags (without "cycle-…" tags), searchable as otag:<tag>.\n` +
  `export const ORACLE_TAGS = ${JSON.stringify(tags)};\n`);
console.log(`Wrote ${tags.length} tags to src/tags.js`);
